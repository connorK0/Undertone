"""Run an offload job on Kaggle's free GPUs, and bring the pool home.

    python -m music_book_gen export <workspace> --arc 0 --overgen 3 --out job.json
    python -m music_book_gen kaggle push   --job job.json --slug music-book-arc0
    python -m music_book_gen kaggle status --slug music-book-arc0
    python -m music_book_gen kaggle pull   --slug music-book-arc0 --out <dir>
    python -m music_book_gen import <workspace> --job job.json \
        --results <dir>/beds-gpu0 <dir>/beds-gpu1 --out <staging dir>

Once, by hand: phone-verify the Kaggle account (GPU and internet both need
it -- the kernel downloads the model), then `kaggle auth login`, which keeps
its token under ~/.kaggle, outside the repo.

This is transport only; what runs there is runner.py unchanged, and the
cull happens at home on import (music_book_gen.jobs). What Kaggle shapes:

  * **T4 x2, not the P100.** Kaggle's PyTorch no longer supports the P100
    (Pascal, sm_60, dropped from torch 2.8's CUDA 12.8 builds).
  * **Two GPUs, so two runners.** The job's takes are dealt round-robin
    across the cards, one runner.py each. The decode loop is bound by
    the CPU with the GPU half idle (SUMMARY 9.37), so two processes on two
    cards should come close to twice the throughput. Unmeasured.
  * **One file goes up.** A pushed kernel is a script; the job, runner.py
    and loopify.py travel inside it, base64-encoded, so there is no dataset to
    upload and version. The kernel is private. The job holds prompts only --
    no book text (music_book_gen.jobs).
  * **About 12 hours a session.** The runners get --stop-after with room to
    spare, so they write their manifests before Kaggle ends the session.
    Anything not started is reported missing by import; export it as a job of
    its own and import both results.
  * **Kaggle's own torch, transformers pinned.** Reinstalling torch would spend
    session time for no parity: sampling on different hardware diverges at
    the same seed anyway. transformers is pinned to phase1/.venv's version,
    because it is the model code.
"""

import argparse
import base64
import json
import subprocess
import sys
from pathlib import Path

TOOL = Path(__file__).resolve().parent
ACCELERATOR = "NvidiaTeslaT4"
TRANSFORMERS = "5.16.1"

# The script that runs on Kaggle. Filled in by build_kernel; kept as one
# template so what goes up can be read in one place.
KERNEL = r'''# Generated by framework/python/music_book_gen/kaggle.py. Re-push rather than edit.
import base64, json, os, subprocess, sys, time
from pathlib import Path

FILES = __FILES__
BUDGET = __BUDGET__
TRANSFORMERS = "__TRANSFORMERS__"

started = time.time()
src = Path("/kaggle/tmp/offload")
src.mkdir(parents=True, exist_ok=True)
for name, data in FILES.items():
    (src / name).write_bytes(base64.b64decode(data))
job = json.loads((src / "job.json").read_text(encoding="utf-8"))

subprocess.check_call([sys.executable, "-m", "pip", "install", "-q",
                       f"transformers=={TRANSFORMERS}", "soundfile"])
# The weights once, before two runners race each other for them.
subprocess.check_call([sys.executable, "-c",
                       "from huggingface_hub import snapshot_download; "
                       f"snapshot_download({job['settings']['model']!r})"])

listing = subprocess.run(["nvidia-smi", "-L"], capture_output=True,
                         text=True).stdout
print(listing, flush=True)
gpus = max(1, listing.count("GPU "))

# Deal the takes round-robin, so each card gets a share of every cue.
for k in range(gpus):
    part = dict(job, sets=[dict(s, cues=s["cues"][k::gpus])
                           for s in job["sets"]])
    (src / f"job-gpu{k}.json").write_text(json.dumps(part), encoding="utf-8")

left = int(BUDGET - (time.time() - started))
procs = []
for k in range(gpus):
    log = open(f"/kaggle/working/beds-gpu{k}.log", "w")
    procs.append(subprocess.Popen(
        [sys.executable, "-u", str(src / "runner.py"),
         str(src / f"job-gpu{k}.json"), "--out", f"/kaggle/working/beds-gpu{k}",
         "--stop-after", str(left)],
        env=dict(os.environ, CUDA_VISIBLE_DEVICES=str(k)),
        stdout=log, stderr=subprocess.STDOUT))
print(f"{gpus} runner(s), {left} s of budget each", flush=True)

# Progress for the kernel's own log, which is all Kaggle shows while it runs.
# Checked often and printed seldom: the first version slept five minutes at a
# time and held a finished session open for four of them, on the quota.
total = sum(len(s["cues"]) for s in job["sets"])
shown = time.time()
while any(p.poll() is None for p in procs):
    time.sleep(15)
    if time.time() - shown >= 300:
        shown = time.time()
        settled = sum(1 for _ in Path("/kaggle/working").glob(
            "beds-gpu*/*/*.report.json"))
        print(f"{(time.time() - started) / 60:6.1f} min  {settled}/{total} "
              f"settled", flush=True)

codes = [p.wait() for p in procs]
for k in range(gpus):
    tail = Path(f"/kaggle/working/beds-gpu{k}.log").read_text().splitlines()[-4:]
    print(f"--- gpu {k}, exit {codes[k]}\n" + "\n".join(tail), flush=True)
print(f"done in {(time.time() - started) / 60:.1f} min", flush=True)
sys.exit(1 if any(codes) else 0)
'''


def kaggle_user() -> str:
    """The logged-in account, however it logged in."""
    from kaggle.api.kaggle_api_extended import KaggleApi
    api = KaggleApi()
    api.authenticate()
    return api.get_config_value("username")


def kaggle(*args: str) -> int:
    return subprocess.call([sys.executable, "-m", "kaggle", *args])


def build_kernel(job: Path, folder: Path, ref: str, hours: float) -> None:
    files = {name: base64.b64encode(path.read_bytes()).decode("ascii")
             for name, path in (("job.json", job),
                                ("runner.py", TOOL / "runner.py"),
                                ("loopify.py", TOOL / "loopify.py"))}
    script = (KERNEL.replace("__FILES__", json.dumps(files))
              .replace("__BUDGET__", str(int(hours * 3600)))
              .replace("__TRANSFORMERS__", TRANSFORMERS))
    folder.mkdir(parents=True, exist_ok=True)
    (folder / "run.py").write_text(script, encoding="utf-8")
    slug = ref.split("/", 1)[1]
    (folder / "kernel-metadata.json").write_text(json.dumps({
        "id": ref,
        # Kaggle derives the slug from the title, and warns if they differ.
        "title": slug.replace("-", " "),
        "code_file": "run.py",
        "language": "python",
        "kernel_type": "script",
        "is_private": True,
        "enable_gpu": True,
        "enable_internet": True,
        "machine_shape": ACCELERATOR,
        "dataset_sources": [],
        "kernel_sources": [],
        "competition_sources": [],
        "model_sources": [],
    }, indent=2) + "\n", encoding="utf-8")


def main(argv: list[str] | None = None) -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    sub = parser.add_subparsers(dest="command", required=True)
    push = sub.add_parser("push", help="send a job to Kaggle and start it")
    push.add_argument("--job", required=True)
    push.add_argument("--slug", required=True,
                      help="the kernel's name, lowercase-and-hyphens; pushing "
                           "the same slug again runs a new version of it")
    push.add_argument("--hours", type=float, default=10.5,
                      help="start nothing new after this long, so the runners "
                           "finish writing inside Kaggle's ~12 h session")
    status = sub.add_parser("status", help="is it running, done, or failed")
    status.add_argument("--slug", required=True)
    pull = sub.add_parser("pull", help="download what the run wrote")
    pull.add_argument("--slug", required=True)
    pull.add_argument("--out", required=True)
    args = parser.parse_args(argv)

    ref = f"{kaggle_user()}/{args.slug}"
    if args.command == "push":
        job = Path(args.job).resolve()
        folder = job.parent / f"kaggle-{args.slug}"
        build_kernel(job, folder, ref, args.hours)
        print(f"{ref}: {folder / 'run.py'} "
              f"({(folder / 'run.py').stat().st_size // 1024} KB)", flush=True)
        sys.exit(kaggle("kernels", "push", "-p", str(folder),
                        "--accelerator", ACCELERATOR))
    if args.command == "status":
        sys.exit(kaggle("kernels", "status", ref))
    out = Path(args.out).resolve()
    out.mkdir(parents=True, exist_ok=True)
    code = kaggle("kernels", "output", ref, "-p", str(out), "-o")
    runs = sorted(p.name for p in out.glob("beds-gpu*") if p.is_dir())
    print(f"next: python -m music_book_gen import <workspace> --job <job.json> --results "
          + " ".join(str(out / r) for r in runs) + " --out <staging dir>")
    sys.exit(code)


if __name__ == "__main__":
    main()
